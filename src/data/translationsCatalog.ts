// Lowercase index for fast case-insensitive lookup
const LOWERCASE_MAP = new Map<string, Record<Language, string>>();
for (const [key, val] of Object.entries(GLOBAL_TRANSLATIONS)) {
  LOWERCASE_MAP.set(key.toLowerCase().trim(), val);
}

/**
 * Translates a user-visible English phrase into the target language.
 */
export function translateText(text: string, lang: Language): string {
  if (!text || lang === 'en') return text;
  const clean = text.trim();
  
  // Exact match
  if (GLOBAL_TRANSLATIONS[clean] && GLOBAL_TRANSLATIONS[clean][lang]) {
    return GLOBAL_TRANSLATIONS[clean][lang];
  }
  
  // Case-insensitive match
  const lower = clean.toLowerCase();
  if (LOWERCASE_MAP.has(lower)) {
    const record = LOWERCASE_MAP.get(lower)!;
    if (record[lang]) return record[lang];
  }

  // Handle common patterns like numbers, colons, brackets
  // e.g. "Total Projects (12)"
  const bracketMatch = clean.match(/^(.+?)\s*\(([^)]+)\)$/);
  if (bracketMatch) {
    const base = bracketMatch[1].trim();
    const inside = bracketMatch[2].trim();
    const transBase = translateText(base, lang);
    if (transBase !== base) {
      return `${transBase} (${inside})`;
    }
  }

  // e.g. "Officer Name:"
  if (clean.endsWith(':')) {
    const withoutColon = clean.slice(0, -1).trim();
    const transWithout = translateText(withoutColon, lang);
    if (transWithout !== withoutColon) {
      return transWithout + ':';
    }
  }

  return text;
}

// Memory maps for seamless bidirectional translation without data loss
const originalTextMap = new WeakMap<Node, string>();
const originalAttrMap = new WeakMap<Element, Record<string, string>>();

/**
 * Recursively applies translations to all text nodes and user-facing attributes.
 */
export function applyTranslationsToElement(el: Node, lang: Language) {
  if (lang === 'en') {
    // Restore original text
    if (el.nodeType === Node.TEXT_NODE) {
      if (originalTextMap.has(el)) {
        const orig = originalTextMap.get(el)!;
        if (el.nodeValue !== orig) {
          el.nodeValue = orig;
        }
      }
    } else if (el.nodeType === Node.ELEMENT_NODE) {
      const elem = el as HTMLElement;
      if (originalAttrMap.has(elem)) {
        const attrs = originalAttrMap.get(elem)!;
        for (const [attr, orig] of Object.entries(attrs)) {
          if (elem.getAttribute(attr) !== orig) {
            elem.setAttribute(attr, orig);
          }
        }
      }
      for (let child = el.firstChild; child; child = child.nextSibling) {
        applyTranslationsToElement(child, lang);
      }
    }
    return;
  }

  if (el.nodeType === Node.TEXT_NODE) {
    const parent = el.parentElement;
    if (parent) {
      const tag = parent.tagName;
      if (tag === 'SCRIPT' || tag === 'STYLE' || tag === 'NOSCRIPT') return;
      if (tag === 'INPUT' || tag === 'TEXTAREA') return;
    }
    const currentVal = el.nodeValue || '';
    if (!originalTextMap.has(el)) {
      originalTextMap.set(el, currentVal);
    }
    const orig = originalTextMap.get(el)!;
    const trimmed = orig.trim();
    if (trimmed.length > 0) {
      const translated = translateText(trimmed, lang);
      if (translated && translated !== trimmed) {
        const leading = orig.match(/^\s*/)?.[0] || '';
        const trailing = orig.match(/\s*$/)?.[0] || '';
        const finalVal = leading + translated + trailing;
        if (el.nodeValue !== finalVal) {
          el.nodeValue = finalVal;
        }
      }
    }
  } else if (el.nodeType === Node.ELEMENT_NODE) {
    const elem = el as HTMLElement;
    const attrsToTranslate = ['placeholder', 'title', 'aria-label'];
    for (const attr of attrsToTranslate) {
      const val = elem.getAttribute(attr);
      if (val && val.trim().length > 0) {
        if (!originalAttrMap.has(elem)) {
          originalAttrMap.set(elem, {});
        }
        const record = originalAttrMap.get(elem)!;
        if (!(attr in record)) {
          record[attr] = val;
        }
        const orig = record[attr];
        const translated = translateText(orig.trim(), lang);
        if (translated && translated !== orig) {
          elem.setAttribute(attr, translated);
        }
      }
    }

    for (let child = el.firstChild; child; child = child.nextSibling) {
      applyTranslationsToElement(child, lang);
    }
  }
}

/**
 * Attaches real-time DOM translation engine and observers.
 * Automatically translates the complete prototype whenever language changes or DOM updates.
 */
export function setupAutoTranslation(getLang: () => Language): () => void {
  let isTranslating = false;

  const runTranslation = () => {
    if (typeof document === 'undefined' || isTranslating) return;
    isTranslating = true;
    try {
      const currentLang = getLang();
      document.documentElement.lang = currentLang;
      document.documentElement.dir = (currentLang === 'ur' ? 'rtl' : 'ltr');
      applyTranslationsToElement(document.body, currentLang);
    } finally {
      isTranslating = false;
    }
  };

  runTranslation();

  let timeout: any = null;
  const observer = new MutationObserver((mutations) => {
    if (isTranslating) return;
    if (timeout) clearTimeout(timeout);
    timeout = setTimeout(() => {
      runTranslation();
    }, 40);
  });

  observer.observe(document.body, {
    childList: true,
    subtree: true,
    attributes: false,
    characterData: false,
  });

  return () => {
    observer.disconnect();
    if (timeout) clearTimeout(timeout);
  };
}
